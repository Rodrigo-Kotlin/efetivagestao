-- ============================================================
-- J. fn_validate_commercial_price_version — publish readiness validator
-- ============================================================
-- Read-only JSONB result. Does NOT mutate data. Authoritative gate for
-- fn_publish_commercial_price_version. Does NOT reimplement pricing
-- formulas — it inspects trusted snapshots and explicit stored values
-- only (DEC-040 + section 40 invariant).

CREATE OR REPLACE FUNCTION public.fn_validate_commercial_price_version(
  p_version_id uuid
)
RETURNS jsonb AS $$
DECLARE
  v_user_id    uuid;
  v_org_id     uuid;
  v_status     text;
  v_item_count integer;
  v_pending_exc integer;
  v_denied_exc  integer;
  v_required_exc_codes text[] := ARRAY[]::text[];
  v_missing_codes text[] := ARRAY[]::text[];
  v_violations_count integer := 0;
  v_blockers text[] := ARRAY[]::text[];
  v_item record;
  v_snap_violations text[];
  v_needed_codes text[];
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  SELECT v.organization_id, v.status
  INTO v_org_id, v_status
  FROM commercial_price_table_versions v
  WHERE v.id = p_version_id;

  IF v_org_id IS NULL THEN
    RAISE EXCEPTION 'Version not found';
  END IF;

  IF NOT is_member_of(v_org_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.view', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.view)';
  END IF;

  -- Item count
  SELECT count(*) INTO v_item_count
  FROM commercial_price_items
  WHERE commercial_price_table_version_id = p_version_id;

  -- Pending + denied exceptions
  SELECT count(*) INTO v_pending_exc
  FROM commercial_price_exceptions
  WHERE commercial_price_table_version_id = p_version_id
    AND status = 'requested';

  SELECT count(*) INTO v_denied_exc
  FROM commercial_price_exceptions
  WHERE commercial_price_table_version_id = p_version_id
    AND status = 'denied';

  -- Compute required exception codes from trusted engine provenance only
  FOR v_item IN
    SELECT id, price_amount, origin_type,
           source_total_cost, source_effective_price, pricing_snapshot
    FROM commercial_price_items
    WHERE commercial_price_table_version_id = p_version_id
  LOOP
    IF v_item.origin_type <> 'pricing_engine' THEN
      CONTINUE;
    END IF;

    v_needed_codes := ARRAY[]::text[];

    -- BELOW_COST: explicit stored comparison (NOT a recomputation)
    IF v_item.source_total_cost IS NOT NULL
       AND v_item.price_amount < v_item.source_total_cost THEN
      v_needed_codes := array_append(v_needed_codes, 'BELOW_COST');
    END IF;

    -- COMMERCIAL_DEVIATION: price below source_effective_price
    IF v_item.source_effective_price IS NOT NULL
       AND v_item.price_amount < v_item.source_effective_price THEN
      v_needed_codes := array_append(v_needed_codes, 'COMMERCIAL_DEVIATION');
    END IF;

    -- BELOW_MINIMUM_MARGIN: from trusted pricing_snapshot only
    IF v_item.pricing_snapshot IS NOT NULL AND jsonb_typeof(v_item.pricing_snapshot) = 'array' THEN
      SELECT COALESCE(array_agg(value #>> '{}'), ARRAY[]::text[])
      INTO v_snap_violations
      FROM jsonb_array_elements(v_item.pricing_snapshot) AS value
      WHERE value #>> '{}' = 'BELOW_MINIMUM_MARGIN';

      IF array_length(v_snap_violations, 1) > 0 THEN
        v_needed_codes := array_append(v_needed_codes, 'BELOW_MINIMUM_MARGIN');
      END IF;
    ELSIF v_item.pricing_snapshot IS NOT NULL
          AND v_item.pricing_snapshot ? 'violations'
          AND jsonb_typeof(v_item.pricing_snapshot->'violations') = 'array' THEN
      IF v_item.pricing_snapshot->'violations' ? 'BELOW_MINIMUM_MARGIN' THEN
        v_needed_codes := array_append(v_needed_codes, 'BELOW_MINIMUM_MARGIN');
      END IF;
    END IF;

    -- For each needed code, ensure an APPROVED exception exists
    IF array_length(v_needed_codes, 1) > 0 THEN
      SELECT array_agg(c) INTO v_required_exc_codes
      FROM unnest(v_needed_codes) AS c
      WHERE NOT EXISTS (
        SELECT 1 FROM commercial_price_exceptions cpe
        WHERE cpe.commercial_price_item_id = v_item.id
          AND cpe.violation_code = c
          AND cpe.status = 'approved'
      );

      IF v_required_exc_codes IS NOT NULL AND array_length(v_required_exc_codes, 1) > 0 THEN
        v_missing_codes := array_cat(v_missing_codes, v_required_exc_codes);
      END IF;

      v_violations_count := v_violations_count + array_length(v_needed_codes, 1);
    END IF;
  END LOOP;

  -- Compose blockers
  IF v_status <> 'approved' THEN
    v_blockers := array_append(v_blockers, 'VERSION_NOT_APPROVED:' || v_status);
  END IF;
  IF v_item_count = 0 THEN
    v_blockers := array_append(v_blockers, 'VERSION_EMPTY');
  END IF;
  IF v_pending_exc > 0 THEN
    v_blockers := array_append(v_blockers, 'PENDING_EXCEPTIONS');
  END IF;
  IF v_denied_exc > 0 THEN
    v_blockers := array_append(v_blockers, 'DENIED_EXCEPTIONS');
  END IF;
  IF array_length(v_missing_codes, 1) > 0 THEN
    v_blockers := array_append(v_blockers, 'MISSING_APPROVED_EXCEPTIONS');
  END IF;

  RETURN jsonb_build_object(
    'version_id', p_version_id,
    'organization_id', v_org_id,
    'status', v_status,
    'ready', array_length(v_blockers, 1) IS NULL,
    'blockers', to_jsonb(v_blockers),
    'warnings', to_jsonb(ARRAY[]::text[]),
    'item_count', v_item_count,
    'pending_exception_count', v_pending_exc,
    'denied_exception_count', v_denied_exc,
    'required_exception_count', v_violations_count,
    'missing_exception_codes', to_jsonb(COALESCE(v_missing_codes, ARRAY[]::text[]))
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER STABLE SET search_path = public;

REVOKE EXECUTE ON FUNCTION public.fn_validate_commercial_price_version(uuid) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_validate_commercial_price_version(uuid) FROM anon;
GRANT EXECUTE ON FUNCTION public.fn_validate_commercial_price_version(uuid) TO authenticated;

-- ============================================================
-- K. fn_publish_commercial_price_version — approved → active/scheduled
-- ============================================================
-- Mirrors the cost module temporal semantics (DEC-028/029):
--   - valid_from <= current_date  → new version becomes active; all
--     other active/scheduled versions for this table are superseded
--     (EXCLUDE constraint satisfied because they leave the WHERE clause).
--   - valid_from >  current_date  → new version becomes scheduled; the
--     current active predecessor stays active with valid_to closed to
--     the new valid_from; only OVERLAPPING scheduled versions are
--     superseded (EXCLUDE satisfied by adjacency).

CREATE OR REPLACE FUNCTION public.fn_publish_commercial_price_version(
  p_version_id uuid
)
RETURNS void AS $$
DECLARE
  v_user_id    uuid;
  v_org_id     uuid;
  v_status     text;
  v_valid_from date;
  v_valid_to   date;
  v_table_id   uuid;
  v_table_status text;
  v_new_status text;
  v_ready      jsonb;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  SELECT v.organization_id, v.status, v.valid_from, v.valid_to, v.commercial_price_table_id
  INTO v_org_id, v_status, v_valid_from, v_valid_to, v_table_id
  FROM commercial_price_table_versions v
  WHERE v.id = p_version_id;

  IF v_org_id IS NULL THEN
    RAISE EXCEPTION 'Version not found';
  END IF;

  IF NOT is_member_of(v_org_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.publish', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.publish)';
  END IF;

  IF v_status <> 'approved' THEN
    RAISE EXCEPTION 'Only approved versions can be published (current status=%)', v_status;
  END IF;

  SELECT status INTO v_table_status
  FROM commercial_price_tables
  WHERE id = v_table_id;

  IF v_table_status IS NULL THEN
    RAISE EXCEPTION 'Commercial price table not found';
  END IF;

  IF v_table_status <> 'active' THEN
    RAISE EXCEPTION 'Cannot publish: commercial price table is inactive';
  END IF;

  -- Run the publish readiness validator — it is the authoritative gate.
  v_ready := public.fn_validate_commercial_price_version(p_version_id);

  IF NOT (v_ready->>'ready')::boolean THEN
    RAISE EXCEPTION 'Publish validation failed: %', v_ready->'blockers';
  END IF;

  -- Date-driven status
  IF v_valid_from > current_date THEN
    v_new_status := 'scheduled';
  ELSE
    v_new_status := 'active';
  END IF;

  -- Open the commercial RPC gate for the duration of this transaction.
  PERFORM set_config('app.commercial_price_rpc_active', 'true', true);

  IF v_new_status = 'active' THEN
    -- Active publish: supersede ALL other active/scheduled versions for
    -- this table. They leave the EXCLUDE WHERE clause; the new version
    -- is the only active/scheduled row remaining.
    UPDATE commercial_price_table_versions
    SET status = 'superseded',
        superseded_at = now(),
        valid_to = CASE
          WHEN v_valid_from > valid_from THEN v_valid_from
          ELSE valid_to
        END
    WHERE commercial_price_table_id = v_table_id
      AND id != p_version_id
      AND status IN ('active', 'scheduled');
  ELSE
    -- Scheduled publish: keep predecessor ACTIVE, close its valid_to.
    UPDATE commercial_price_table_versions
    SET valid_to = v_valid_from
    WHERE commercial_price_table_id = v_table_id
      AND id != p_version_id
      AND status = 'active'
      AND valid_from < v_valid_from
      AND (valid_to IS NULL OR valid_to > v_valid_from);

    -- Supersede OVERLAPPING scheduled versions (daterange '[)' semantics).
    UPDATE commercial_price_table_versions
    SET status = 'superseded',
        superseded_at = now()
    WHERE commercial_price_table_id = v_table_id
      AND id != p_version_id
      AND status = 'scheduled'
      AND daterange(valid_from, valid_to, '[)') && daterange(v_valid_from, v_valid_to, '[)');
  END IF;

  -- Publish the new version. approved_by/at/published_by/at are derived
  -- by the existing 032 fn_cptv_validate_status_transition trigger.
  UPDATE commercial_price_table_versions
  SET status = v_new_status
  WHERE id = p_version_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE EXECUTE ON FUNCTION public.fn_publish_commercial_price_version(uuid) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_publish_commercial_price_version(uuid) FROM anon;
GRANT EXECUTE ON FUNCTION public.fn_publish_commercial_price_version(uuid) TO authenticated;

-- ============================================================
-- L. fn_sync_commercial_price_version_status — idempotent cutover
-- ============================================================
-- Activates scheduled versions whose valid_from <= reference_date and
-- supersedes the active predecessor. Safe to run repeatedly.

CREATE OR REPLACE FUNCTION public.fn_sync_commercial_price_version_status(
  p_reference_date date DEFAULT current_date
)
RETURNS integer AS $$
DECLARE
  v_user_id uuid;
  v_count   integer := 0;
  v_sched   record;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_reference_date IS NULL THEN
    RAISE EXCEPTION 'Reference date is required';
  END IF;

  PERFORM set_config('app.commercial_price_rpc_active', 'true', true);

  FOR v_sched IN
    SELECT s.id, s.commercial_price_table_id, s.valid_from, s.valid_to, s.organization_id
    FROM commercial_price_table_versions s
    WHERE s.status = 'scheduled'
      AND s.valid_from <= p_reference_date
      AND (s.valid_to IS NULL OR s.valid_to > p_reference_date)
    ORDER BY s.commercial_price_table_id, s.valid_from ASC, s.version_number ASC
  LOOP
    IF NOT has_permission('pricing.commercial.publish', v_sched.organization_id) THEN
      RAISE EXCEPTION 'Insufficient permissions for commercial version activation';
    END IF;

    -- Supersede the active predecessor whose range ends where this begins.
    UPDATE commercial_price_table_versions
    SET status = 'superseded',
        superseded_at = now()
    WHERE commercial_price_table_id = v_sched.commercial_price_table_id
      AND status = 'active'
      AND id NOT IN (
        SELECT s2.id
        FROM commercial_price_table_versions s2
        WHERE s2.commercial_price_table_id = v_sched.commercial_price_table_id
          AND s2.status = 'scheduled'
          AND s2.valid_from <= p_reference_date
          AND (s2.valid_to IS NULL OR s2.valid_to > p_reference_date)
      )
      AND valid_from <= v_sched.valid_from
      AND (valid_to IS NULL OR valid_to >= v_sched.valid_from);

    -- Activate the scheduled version. published_by/at are derived by the
    -- existing 032 fn_cptv_validate_status_transition trigger.
    UPDATE commercial_price_table_versions
    SET status = 'active'
    WHERE id = v_sched.id;

    v_count := v_count + 1;
  END LOOP;

  RETURN v_count;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE EXECUTE ON FUNCTION public.fn_sync_commercial_price_version_status(date) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_sync_commercial_price_version_status(date) FROM anon;
GRANT EXECUTE ON FUNCTION public.fn_sync_commercial_price_version_status(date) TO authenticated;

