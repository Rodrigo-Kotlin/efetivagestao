-- ============================================================
-- F. fn_clone_commercial_price_table_version — atomic clone
-- ============================================================
-- Copies ALL eligible source items atomically. Aborts the whole transaction
-- if any source item references an inactive catalog item (no partial
-- version, no partial item list). Refreshes catalog snapshots from current
-- catalog via the existing 032 snapshot trigger. Preserves lineage to each
-- source item via source_commercial_price_item_id.

CREATE OR REPLACE FUNCTION public.fn_clone_commercial_price_table_version(
  p_source_version_id uuid,
  p_valid_from        date,
  p_valid_to          date DEFAULT NULL,
  p_version_label     text DEFAULT NULL,
  p_notes             text DEFAULT NULL
)
RETURNS TABLE (new_version_id uuid, new_version_number integer) AS $$
DECLARE
  v_user_id        uuid;
  v_org_id         uuid;
  v_table_id       uuid;
  v_version_num    integer;
  v_new_version_id uuid;
  v_source_count   integer;
  v_inactive_count integer;
  v_item           record;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  -- Load source version + parent table
  SELECT v.organization_id, v.commercial_price_table_id
  INTO v_org_id, v_table_id
  FROM commercial_price_table_versions v
  WHERE v.id = p_source_version_id;

  IF v_org_id IS NULL THEN
    RAISE EXCEPTION 'Source version not found';
  END IF;

  IF NOT is_member_of(v_org_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.create', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.create)';
  END IF;

  IF p_valid_to IS NOT NULL AND p_valid_to <= p_valid_from THEN
    RAISE EXCEPTION 'valid_to must be greater than valid_from';
  END IF;

  -- Lock the parent stable table to serialize version_number allocation
  -- and to prevent the parent from being inactivated mid-clone.
  PERFORM 1 FROM commercial_price_tables
  WHERE id = v_table_id
  FOR UPDATE;

  -- Parent-active guard already enforced on version INSERT below, but we
  -- also check here for a clearer error before allocating.

  -- Verify at least one source item exists
  SELECT count(*) INTO v_source_count
  FROM commercial_price_items
  WHERE commercial_price_table_version_id = p_source_version_id;

  IF v_source_count = 0 THEN
    RAISE EXCEPTION 'Cannot clone a version with no items';
  END IF;

  -- Pre-flight: ALL source items must reference an ACTIVE catalog item
  -- (PRC-05A section 40 invariant).
  SELECT count(*) INTO v_inactive_count
  FROM commercial_price_items cpi
  JOIN catalog_items ci ON ci.id = cpi.catalog_item_id
  WHERE cpi.commercial_price_table_version_id = p_source_version_id
    AND ci.status <> 'active';

  IF v_inactive_count > 0 THEN
    RAISE EXCEPTION 'SOURCE_CONTAINS_INACTIVE_CATALOG_ITEM (% inactive catalog item(s) referenced by source items)', v_inactive_count;
  END IF;

  -- Allocate the next version_number under FOR UPDATE on the parent table.
  SELECT COALESCE(MAX(cptv.version_number), 0) + 1
  INTO v_version_num
  FROM commercial_price_table_versions cptv
  WHERE cptv.commercial_price_table_id = v_table_id;

  -- Open the commercial RPC gate for the duration of this transaction
  -- so the A2 engine-provenance guard allows engine-origin items to be
  -- copied with their original provenance/snapshot.
  PERFORM set_config('app.commercial_price_rpc_active', 'true', true);

  -- Create the new draft version. The trg_cptv_parent_active trigger will
  -- verify the parent table is active; the trg_cptv_table_same_org trigger
  -- verifies org consistency.
  INSERT INTO commercial_price_table_versions (
    organization_id, commercial_price_table_id, version_number,
    valid_from, valid_to, status, version_label, notes,
    created_by
  ) VALUES (
    v_org_id, v_table_id, v_version_num,
    p_valid_from, p_valid_to, 'draft', p_version_label, p_notes,
    v_user_id
  ) RETURNING id INTO v_new_version_id;

  -- Copy ALL eligible source items atomically. The existing
  -- fn_cpi_snapshot_derive trigger refreshes catalog snapshots. The A2
  -- guard allows engine-origin items because the gate is set.
  --
  -- Lineage (DEC-049): the cloned item's source_commercial_price_item_id
  -- is ALWAYS set to the source item's id, regardless of what the source
  -- item's own lineage was. Cloning produces a fresh lineage edge that
  -- points to the immediate predecessor (the source item being cloned).
  FOR v_item IN
    SELECT id AS source_item_id,
           catalog_item_id, price_amount, currency, origin_type,
           source_reference_date, source_supplier_company_id,
           source_cost_table_id, source_cost_version_id, source_cost_version_number,
           source_pricing_policy_id, source_pricing_policy_version_id, source_policy_version_number,
           source_calculated_price, source_total_cost,
           source_margin_rate, source_markup_rate, source_effective_price,
           pricing_snapshot
    FROM commercial_price_items
    WHERE commercial_price_table_version_id = p_source_version_id
    ORDER BY id
  LOOP
    INSERT INTO commercial_price_items (
      organization_id, commercial_price_table_version_id, catalog_item_id,
      price_amount, currency, origin_type,
      source_commercial_price_item_id,
      source_reference_date, source_supplier_company_id,
      source_cost_table_id, source_cost_version_id, source_cost_version_number,
      source_pricing_policy_id, source_pricing_policy_version_id, source_policy_version_number,
      source_calculated_price, source_total_cost,
      source_margin_rate, source_markup_rate, source_effective_price,
      pricing_snapshot,
      created_by, updated_by
    ) VALUES (
      v_org_id, v_new_version_id, v_item.catalog_item_id,
      v_item.price_amount, v_item.currency, v_item.origin_type,
      -- Lineage: always point to the immediate predecessor (source item).
      v_item.source_item_id,
      v_item.source_reference_date, v_item.source_supplier_company_id,
      v_item.source_cost_table_id, v_item.source_cost_version_id, v_item.source_cost_version_number,
      v_item.source_pricing_policy_id, v_item.source_pricing_policy_version_id, v_item.source_policy_version_number,
      v_item.source_calculated_price, v_item.source_total_cost,
      v_item.source_margin_rate, v_item.source_markup_rate, v_item.source_effective_price,
      v_item.pricing_snapshot,
      v_user_id, v_user_id
    );
  END LOOP;

  -- DO NOT copy commercial_price_exceptions: approvals are version-specific.

  RETURN QUERY SELECT v_new_version_id, v_version_num;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

