-- PRC-05C: Commercial Price Workflow RPCs + Forward Integrity Hardening
-- Baseline: b2235b659e48b654b64df42e31c6bc68d32a2689 (COMMERCIAL_PRICE_SCHEMA_VERIFIED)
-- Migrations 001-033 are IMMUTABLE.
--
-- This migration delivers the authoritative commercial-price workflow layer over
-- the trusted PRC-05B schema:
--   A. Forward-only integrity hardening discovered during the PRC-05C
--      pre-implementation audit:
--      A1. Inactive commercial_price_tables MUST NOT receive new versions,
--          via RPC OR direct DML (PRC-05A invariant).
--      A2. origin_type = 'pricing_engine' provenance MUST be generated by a
--          trusted server-side RPC. Direct DML fabrication is blocked.
--      A3. New commercial_price_exceptions requests MUST be blocked when
--          the parent version has left the editable lifecycle
--          (scheduled/active/superseded/cancelled).
--   B. Table identity RPCs (create / update / status)
--   C. Concurrency-safe version allocation RPC
--   D. Manual commercial item RPCs (add / update price / delete)
--   E. Trusted engine-derived item RPC (only path to pricing_engine origin)
--   F. Atomic clone version RPC with catalog snapshot refresh + lineage
--   G. Server-side bulk draft price adjustments (percentage / fixed / rounding)
--   H. Commercial exception request / decision RPCs
--   I. Workflow RPCs (submit / return-to-draft / approve / cancel)
--   J. Publish readiness validator (read-only JSONB result)
--   K. Publish RPC (immediate / future / predecessor continuity)
--   L. Idempotent scheduled→active cutover RPC
--   M. Permission / grant / revoke
--
-- Patterns follow PRC-03B/04C conventions:
--   - SECURITY DEFINER + SET search_path = public
--   - Server-derived auth.uid()
--   - app.commercial_price_rpc_active session gate for trigger validation
--   - FOR UPDATE locking for concurrency-safe version allocation
--   - REVOKE FROM PUBLIC/anon; GRANT to authenticated for application-facing

-- ============================================================
-- A1. Inactive parent → no new version (forward integrity)
-- ============================================================
-- PRC-05A section 6 invariant: an inactive commercial_price_tables row cannot
-- receive a new commercial_price_table_versions row via RPC OR direct DML.
-- The existing 032 trigger fn_cptv_table_same_org only enforces org membership;
-- status is NOT enforced. This trigger closes the gap FORWARD-ONLY.

CREATE OR REPLACE FUNCTION public.fn_cptv_parent_active()
RETURNS trigger AS $$
DECLARE
  v_status text;
BEGIN
  SELECT status INTO v_status
  FROM commercial_price_tables
  WHERE id = NEW.commercial_price_table_id;

  IF v_status IS NULL THEN
    RAISE EXCEPTION 'commercial_price_table_id not found';
  END IF;

  IF v_status <> 'active' THEN
    RAISE EXCEPTION 'Cannot create a version of an inactive commercial price table (status=%)', v_status;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = public;

DROP TRIGGER IF EXISTS trg_cptv_parent_active ON commercial_price_table_versions;
CREATE TRIGGER trg_cptv_parent_active
  BEFORE INSERT ON commercial_price_table_versions
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_cptv_parent_active();

-- ============================================================
-- A2. Engine provenance spoof guard (forward integrity)
-- ============================================================
-- PRC-05A invariant: origin_type = 'pricing_engine' provenance MUST come from
-- a trusted server-side RPC that calls fn_simulate_price. Direct browser DML
-- is blocked. The existing 032 fn_cpi_provenance_same_org trigger only checks
-- cross-org FK consistency — it does NOT prevent fabrication.
--
-- Allowed paths:
--   - controlled RPC sets app.commercial_price_rpc_active = 'true'
--     (fn_add_commercial_price_item_from_engine and fn_clone_*)
--   - manual items with origin_type = 'manual' (no gate needed)
-- The gate is required so that the same trigger that blocks fabrication also
-- permits cloning and engine-derived item creation.

CREATE OR REPLACE FUNCTION public.fn_cpi_engine_provenance_guard()
RETURNS trigger AS $$
DECLARE
  v_is_rpc boolean;
BEGIN
  v_is_rpc := COALESCE((current_setting('app.commercial_price_rpc_active', true) = 'true'), false);

  -- No engine provenance involved → allow
  IF NEW.origin_type IS DISTINCT FROM 'pricing_engine' THEN
    RETURN NEW;
  END IF;

  IF NOT v_is_rpc THEN
    RAISE EXCEPTION 'origin_type=pricing_engine provenance must be created via the engine-derived item RPC';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = public;

DROP TRIGGER IF EXISTS trg_cpi_engine_provenance_guard ON commercial_price_items;
CREATE TRIGGER trg_cpi_engine_provenance_guard
  BEFORE INSERT OR UPDATE ON commercial_price_items
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_cpi_engine_provenance_guard();

-- ============================================================
-- A3. Exception parent-state hardening (forward integrity)
-- ============================================================
-- New exception requests MUST be blocked once the parent version has left the
-- editable lifecycle (scheduled / active / superseded / cancelled). Existing
-- 032 fn_cpe_integrity and fn_cpe_status_transition enforce item/version
-- consistency but do NOT enforce parent lifecycle state.
--
-- This invariant is enforced unconditionally (no gate) — no path can create a
-- new exception against a published-lifecycle version.

CREATE OR REPLACE FUNCTION public.fn_cpe_parent_editable()
RETURNS trigger AS $$
DECLARE
  v_status text;
BEGIN
  SELECT status INTO v_status
  FROM commercial_price_table_versions
  WHERE id = NEW.commercial_price_table_version_id;

  IF v_status IS NULL THEN
    RAISE EXCEPTION 'commercial_price_table_version_id not found';
  END IF;

  IF v_status NOT IN ('draft','under_review','approved') THEN
    RAISE EXCEPTION 'Cannot create commercial price exception for version with status % (allowed: draft, under_review, approved)', v_status;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = public;

DROP TRIGGER IF EXISTS trg_cpe_parent_editable ON commercial_price_exceptions;
CREATE TRIGGER trg_cpe_parent_editable
  BEFORE INSERT ON commercial_price_exceptions
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_cpe_parent_editable();

-- ============================================================
-- B1. fn_create_commercial_price_table — stable identity create
-- ============================================================
CREATE OR REPLACE FUNCTION public.fn_create_commercial_price_table(
  p_organization_id uuid,
  p_code            text,
  p_name            text,
  p_description     text DEFAULT NULL
)
RETURNS uuid AS $$
DECLARE
  v_user_id  uuid;
  v_table_id uuid;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF NOT is_member_of(p_organization_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.create', p_organization_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.create)';
  END IF;

  INSERT INTO commercial_price_tables (
    organization_id, code, name, description,
    status, created_by, updated_by
  ) VALUES (
    p_organization_id, p_code, p_name, p_description,
    'active', v_user_id, v_user_id
  ) RETURNING id INTO v_table_id;

  RETURN v_table_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

