-- ============================================================
-- E. fn_add_commercial_price_item_from_engine — trusted engine provenance
-- ============================================================
-- The ONLY trusted way to create origin_type = 'pricing_engine'. Calls the
-- authoritative fn_simulate_price(...) and extracts real provenance keys
-- from the simulation result. Direct browser DML fabrication is blocked by
-- the A2 forward guard.

CREATE OR REPLACE FUNCTION public.fn_add_commercial_price_item_from_engine(
  p_version_id                uuid,
  p_catalog_item_id           uuid,
  p_supplier_company_id       uuid,
  p_reference_date            date    DEFAULT current_date,
  p_discount_rate             numeric DEFAULT 0,
  p_commercial_price_amount   numeric DEFAULT NULL
)
RETURNS uuid AS $$
DECLARE
  v_user_id        uuid;
  v_org_id         uuid;
  v_status         text;
  v_sim            jsonb;
  v_sim_status     text;
  v_item_id        uuid;

  v_prov_org          uuid;
  v_prov_supplier     uuid;
  v_prov_cat_item     uuid;
  v_prov_ref_date     date;

  v_prov_cost_table    uuid;
  v_prov_cost_version  uuid;
  v_prov_cost_ver_num  integer;
  v_prov_cost_valid_from date;
  v_prov_cost_valid_to   date;

  v_prov_policy        uuid;
  v_prov_policy_ver    uuid;
  v_prov_policy_ver_num integer;

  v_calculated_price   numeric;
  v_total_cost         numeric;
  v_margin_rate        numeric;
  v_markup_rate        numeric;
  v_effective_price    numeric;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_discount_rate IS NOT NULL AND (p_discount_rate < 0 OR p_discount_rate > 1) THEN
    RAISE EXCEPTION 'discount_rate must be between 0 and 1';
  END IF;

  IF p_commercial_price_amount IS NOT NULL AND p_commercial_price_amount < 0 THEN
    RAISE EXCEPTION 'commercial_price_amount must be >= 0';
  END IF;

  SELECT v.organization_id, v.status
  INTO v_org_id, v_status
  FROM commercial_price_table_versions v
  WHERE v.id = p_version_id;

  IF v_org_id IS NULL THEN
    RAISE EXCEPTION 'Version not found';
  END IF;

  IF NOT is_member_of(v_org_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.create', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.create)';
  END IF;

  IF NOT has_permission('pricing.calculate', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.calculate)';
  END IF;

  IF v_status <> 'draft' THEN
    RAISE EXCEPTION 'Cannot add engine item to version with status % (only draft allowed)', v_status;
  END IF;

  -- Call authoritative simulation. fn_simulate_price enforces its own auth,
  -- membership and pricing.calculate check — we are double-gating by
  -- permission above for the same effect (defense in depth).
  v_sim := public.fn_simulate_price(
    p_organization_id     => v_org_id,
    p_supplier_company_id => p_supplier_company_id,
    p_catalog_item_id     => p_catalog_item_id,
    p_reference_date      => p_reference_date,
    p_discount_rate       => COALESCE(p_discount_rate, 0)
  );

  v_sim_status := v_sim->>'status';

  IF v_sim_status IS NULL THEN
    RAISE EXCEPTION 'Pricing simulation returned no status';
  END IF;

  -- Accept only business-calculable outcomes
  IF v_sim_status NOT IN ('OK','VIOLATIONS') THEN
    RAISE EXCEPTION 'Pricing simulation not business-calculable: %', v_sim_status;
  END IF;

  -- Extract provenance (use exact keys from fn_simulate_price result)
  v_prov_org       := (v_sim->'provenance'->>'organization_id')::uuid;
  v_prov_supplier  := (v_sim->'provenance'->>'supplier_company_id')::uuid;
  v_prov_cat_item  := (v_sim->'provenance'->>'catalog_item_id')::uuid;
  v_prov_ref_date  := (v_sim->'provenance'->>'reference_date')::date;

  v_prov_cost_table   := (v_sim->'provenance'->'cost'->>'cost_table_id')::uuid;
  v_prov_cost_version := (v_sim->'provenance'->'cost'->>'cost_version_id')::uuid;
