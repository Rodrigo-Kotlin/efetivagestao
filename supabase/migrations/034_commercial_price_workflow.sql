-- ============================================================
-- B2. fn_update_commercial_price_table — stable mutable fields
-- ============================================================
-- Code immutability is enforced by the existing 032 fn_cpt_normalize_code
-- trigger (history-protection). This RPC only mutates name / description.

CREATE OR REPLACE FUNCTION public.fn_update_commercial_price_table(
  p_table_id    uuid,
  p_name        text DEFAULT NULL,
  p_description text DEFAULT NULL
)
RETURNS void AS $$
DECLARE
  v_user_id uuid;
  v_org_id  uuid;
  v_status  text;
  v_has_history boolean;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  SELECT organization_id, status INTO v_org_id, v_status
  FROM commercial_price_tables
  WHERE id = p_table_id
  FOR UPDATE;

  IF v_org_id IS NULL THEN
    RAISE EXCEPTION 'Commercial price table not found';
  END IF;

  IF NOT is_member_of(v_org_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.edit', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.edit)';
  END IF;

  -- Inactive tables retain historical versions but cannot be edited for new
  -- workflow. Allow editing identity only when the table is active (so an
  -- existing commercial operator can still fix typos before creating more
  -- versions). Reactivation re-enables full edit lifecycle.
  IF v_status <> 'active' THEN
    RAISE EXCEPTION 'Cannot edit inactive commercial price table';
  END IF;

  -- At least one field must be provided
  IF p_name IS NULL AND p_description IS NULL THEN
    RAISE EXCEPTION 'At least one of name or description must be provided';
  END IF;

  -- Reject empty/whitespace name if explicitly provided
  IF p_name IS NOT NULL AND btrim(p_name) = '' THEN
    RAISE EXCEPTION 'name cannot be empty or whitespace only';
  END IF;

  UPDATE commercial_price_tables
  SET name        = COALESCE(p_name, name),
      description = CASE WHEN p_description IS NULL THEN description ELSE p_description END,
      updated_by  = v_user_id
  WHERE id = p_table_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE EXECUTE ON FUNCTION public.fn_update_commercial_price_table(uuid, text, text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_update_commercial_price_table(uuid, text, text) FROM anon;
GRANT EXECUTE ON FUNCTION public.fn_update_commercial_price_table(uuid, text, text) TO authenticated;

-- ============================================================
-- B3. fn_set_commercial_price_table_status — active ↔ inactive
-- ============================================================
-- Inactivation must NOT mutate or supersede existing published versions;
-- historical reproducibility must be preserved (table-specific resolver still
-- works for any historical reference date). Reactivation is supported.

CREATE OR REPLACE FUNCTION public.fn_set_commercial_price_table_status(
  p_table_id uuid,
  p_status   text
)
RETURNS void AS $$
DECLARE
  v_user_id uuid;
  v_org_id  uuid;
  v_current text;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_status IS NULL OR p_status NOT IN ('active','inactive') THEN
    RAISE EXCEPTION 'Invalid status % (allowed: active, inactive)', p_status;
  END IF;

  SELECT organization_id, status INTO v_org_id, v_current
  FROM commercial_price_tables
  WHERE id = p_table_id
  FOR UPDATE;

  IF v_org_id IS NULL THEN
    RAISE EXCEPTION 'Commercial price table not found';
  END IF;

  IF NOT is_member_of(v_org_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.edit', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.edit)';
  END IF;

  IF v_current = p_status THEN
    RETURN;
  END IF;

  -- Inactivation: do not mutate/supersede existing published versions.
  -- (Reactivation is a no-op for the published versions themselves.)
  UPDATE commercial_price_tables
  SET status     = p_status,
      updated_by = v_user_id
  WHERE id = p_table_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE EXECUTE ON FUNCTION public.fn_set_commercial_price_table_status(uuid, text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_set_commercial_price_table_status(uuid, text) FROM anon;
GRANT EXECUTE ON FUNCTION public.fn_set_commercial_price_table_status(uuid, text) TO authenticated;

-- ============================================================
-- C. fn_create_commercial_price_table_version — concurrency-safe allocation
-- ============================================================
-- Locks the parent commercial_price_tables row FOR UPDATE so that two
-- concurrent calls produce distinct consecutive version_numbers (DEC-044
-- applied to commercial versions).

CREATE OR REPLACE FUNCTION public.fn_create_commercial_price_table_version(
  p_commercial_price_table_id uuid,
  p_valid_from                date,
  p_valid_to                  date DEFAULT NULL,
  p_version_label             text DEFAULT NULL,
  p_notes                     text DEFAULT NULL
)
RETURNS TABLE (version_id uuid, version_number integer) AS $$
DECLARE
  v_user_id      uuid;
  v_org_id       uuid;
  v_version_num  integer;
  v_version_id   uuid;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  -- Lock the parent stable table to serialize version_number allocation.
  SELECT cpt.organization_id INTO v_org_id
  FROM commercial_price_tables cpt
  WHERE cpt.id = p_commercial_price_table_id
  FOR UPDATE;

  IF v_org_id IS NULL THEN
    RAISE EXCEPTION 'Commercial price table not found';
  END IF;

  IF NOT is_member_of(v_org_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.create', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.create)';
  END IF;

  -- Parent-active guard already enforced by trg_cptv_parent_active.

  IF p_valid_to IS NOT NULL AND p_valid_to <= p_valid_from THEN
    RAISE EXCEPTION 'valid_to must be greater than valid_from';
  END IF;

  -- Alias the table column to avoid ambiguity with the OUT parameter
  -- named `version_number` (PL/pgSQL RETURNS TABLE column name).
  SELECT COALESCE(MAX(cptv.version_number), 0) + 1
  INTO v_version_num
  FROM commercial_price_table_versions cptv
  WHERE cptv.commercial_price_table_id = p_commercial_price_table_id;

  INSERT INTO commercial_price_table_versions (
    organization_id, commercial_price_table_id, version_number,
    valid_from, valid_to, status, version_label, notes,
    created_by
  ) VALUES (
    v_org_id, p_commercial_price_table_id, v_version_num,
    p_valid_from, p_valid_to, 'draft', p_version_label, p_notes,
    v_user_id
  ) RETURNING id INTO v_version_id;

  RETURN QUERY SELECT v_version_id, v_version_num;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE EXECUTE ON FUNCTION public.fn_create_commercial_price_table_version(uuid, date, date, text, text) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.fn_create_commercial_price_table_version(uuid, date, date, text, text) FROM anon;
GRANT EXECUTE ON FUNCTION public.fn_create_commercial_price_table_version(uuid, date, date, text, text) TO authenticated;

