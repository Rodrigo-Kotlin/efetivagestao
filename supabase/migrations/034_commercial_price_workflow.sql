-- ============================================================
-- G. fn_bulk_adjust_commercial_prices — server-side bulk adjustments
-- ============================================================
-- Atomic percentage / fixed / rounding operations on draft items only.
-- Uses PostgreSQL numeric for authoritative arithmetic. Resulting price
-- is persisted as the new explicit price_amount; no live formula is stored.

CREATE OR REPLACE FUNCTION public.fn_bulk_adjust_commercial_prices(
  p_version_id        uuid,
  p_operation         text,    -- 'percentage' | 'fixed' | 'round'
  p_rate              numeric DEFAULT NULL,   -- percentage as fraction (e.g. 0.05)
  p_fixed_amount      numeric DEFAULT NULL,   -- signed amount to add
  p_rounding_mode     text    DEFAULT NULL,   -- 'nearest' | 'up' | 'down'
  p_rounding_step     numeric DEFAULT NULL,   -- positive step
  p_item_ids          uuid[]  DEFAULT NULL    -- NULL = all items in version
)
RETURNS integer AS $$
DECLARE
  v_user_id      uuid;
  v_org_id       uuid;
  v_status       text;
  v_updated      integer := 0;
  v_rec          record;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  IF p_operation NOT IN ('percentage','fixed','round') THEN
    RAISE EXCEPTION 'Invalid operation % (allowed: percentage, fixed, round)', p_operation;
  END IF;

  SELECT v.organization_id, v.status
  INTO v_org_id, v_status
  FROM commercial_price_table_versions v
  WHERE v.id = p_version_id;

  IF v_org_id IS NULL THEN
    RAISE EXCEPTION 'Version not found';
  END IF;

  IF NOT is_member_of(v_org_id) THEN
    RAISE EXCEPTION 'Not a member of this organization';
  END IF;

  IF NOT has_permission('pricing.commercial.edit', v_org_id) THEN
    RAISE EXCEPTION 'Insufficient permissions (requires pricing.commercial.edit)';
  END IF;

  IF v_status <> 'draft' THEN
    RAISE EXCEPTION 'Bulk operations only allowed on draft versions (status=%)', v_status;
  END IF;

  -- Pre-flight parameter validation (per-operation requirements). Catching
  -- these here avoids invalid SQL inside the CASE expressions of the per-row
  -- UPDATE below (RAISE is a PL/pgSQL statement, not an expression).
  IF p_operation = 'percentage' AND p_rate IS NULL THEN
    RAISE EXCEPTION 'percentage requires rate';
  END IF;
  IF p_operation = 'fixed' AND p_fixed_amount IS NULL THEN
    RAISE EXCEPTION 'fixed requires fixed_amount';
  END IF;
  IF p_operation = 'round' AND (
       p_rounding_mode IS NULL OR p_rounding_step IS NULL OR p_rounding_step <= 0
     ) THEN
    RAISE EXCEPTION 'round requires mode and positive step';
  END IF;
  IF p_operation = 'round' AND p_rounding_mode NOT IN ('nearest','up','down') THEN
    RAISE EXCEPTION 'Invalid rounding mode %', p_rounding_mode;
  END IF;

  -- Open the commercial RPC gate so the A2 guard allows updates to
  -- engine-origin items (their origin_type remains unchanged; the guard
  -- still fires because UPDATE is allowed to keep engine provenance).
  PERFORM set_config('app.commercial_price_rpc_active', 'true', true);

  -- Iterate item-by-item so each UPDATE is atomic and individually validated
  -- against the negative-price constraint. The fn_cpi_parent_draft trigger
  -- and the existing fn_cpi_actor trigger ensure actor derivation.
  FOR v_rec IN
    SELECT id, price_amount
    FROM commercial_price_items
    WHERE commercial_price_table_version_id = p_version_id
      AND (p_item_ids IS NULL OR id = ANY(p_item_ids))
  LOOP
    UPDATE commercial_price_items
    SET price_amount = CASE p_operation
          WHEN 'percentage' THEN v_rec.price_amount * (1 + p_rate)
          WHEN 'fixed'      THEN v_rec.price_amount + p_fixed_amount
          WHEN 'round'      THEN
            CASE p_rounding_mode
              WHEN 'nearest' THEN round(v_rec.price_amount / p_rounding_step) * p_rounding_step
              WHEN 'up'     THEN ceil(v_rec.price_amount / p_rounding_step)  * p_rounding_step
              WHEN 'down'   THEN floor(v_rec.price_amount / p_rounding_step) * p_rounding_step
            END
        END,
        updated_by   = v_user_id
    WHERE id = v_rec.id;

    v_updated := v_updated + 1;
  END LOOP;

  -- Final atomic validation: ensure all updated items are still >= 0.
  -- The CHECK constraint at the column level blocks negative values per
  -- UPDATE, but we double-check for clarity.
  IF EXISTS (
    SELECT 1 FROM commercial_price_items
    WHERE commercial_price_table_version_id = p_version_id
      AND (p_item_ids IS NULL OR id = ANY(p_item_ids))
      AND price_amount < 0
  ) THEN
    RAISE EXCEPTION 'Bulk adjustment produced a negative price_amount';
  END IF;

  RETURN v_updated;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

